"""
TNDQ_real 真机参数覆写 —— 导入本模块即完成 config.params 的真机口径切换。

★ 必须在 `from experiments import run_lib` 之前导入 ★
原理：run_lib 在 import 期以 `from config.params import DT, CTRL_EVERY,
...` 固化参数名；本模块先行修改 config.params 模块属性，run_lib 随后
读到的即为真机口径。理论层（core/control 数学）零改动。

注意：config/params.py 侧的 CTRL_USE_REAL_RATE 已按要求切 True（真机
部署口径），仿真性能上界复测时将其改回 False 即可还原 2 ms 口径。
"""
import numpy as np

import config.params as cp

# ---------------------------------------------------------------------------
# [1] 时间基准：真机没有 2 ms 物理步，控制周期 = 唯一时间基准
#     CTRL_DT = 0.01（10 ms）已在 params.py 定义；此处把 DT 对齐它，
#     CTRL_EVERY 强制 1（总线层 500 Hz 零阶保持在 RealB601Backend 内部
#     完成，对 run_lib 透明——等价于仿真 CTRL_EVERY=5 的 ZOH 工况）。
# ---------------------------------------------------------------------------
cp.DT = cp.CTRL_DT                       # 10 ms（Jetson 反馈计算预算）
cp.CTRL_EVERY = 1                        # 每 DT 步 = 一次控制计算

# ---------------------------------------------------------------------------
# [2] 增益组：small_arm 即为本工况设计（params.py GAIN_SETS 注释：
#     小型臂硬件精度低 + 真机反馈 ~10 ms，高刚度放大残差成振荡；
#     通道极点 {-2,-8}，定理 3(c) 证书裕量充足）。04 空载跑通后
#     若稳态偏差偏大，可试 "grasp" 组（e_ss 更小，先确认无振荡）。
# ---------------------------------------------------------------------------
cp.DEFAULT_GAIN_SET = "small_arm"

# ---------------------------------------------------------------------------
# [3] 关节阻尼注入：仿真中该项的物理对应就是真机电机阻尼/减速器摩擦
#     （params.py JOINT_DAMPING 注释"部署时天然存在"）。真机保留小值
#     兜底轻腕漂移，依据空载 CSV 稳态蠕动情况上下调整（过阻尼征兆：
#     跟踪滞后明显增大；欠阻尼征兆：腕关节慢漂）。
# ---------------------------------------------------------------------------
cp.JOINT_DAMPING = 0.01 * np.ones(6)     # [N*m*s/rad]（仿真值 0.02 减半起步）

# ---------------------------------------------------------------------------
# [4] 速度治理收紧：首跑阶段额定速度上限 3.0 -> 1.0 rad/s（goto 轨迹
#     关节速度峰值 < 1 rad/s，不影响任务执行；跑通后恢复 3.0）。
#     限位保护/预测制动/奇异阻尼等其余安全逻辑原样保留（run_lib 层）。
# ---------------------------------------------------------------------------
cp.QDOT_MAX = 1.0 * np.ones(6)           # [rad/s]（首跑保守值）

# ---------------------------------------------------------------------------
# [5] 仿真器专有机制确认真机关闭（dither 为 PhysX TGS 构型锁对策，
#     真机无此病理；params.py 现值已 False，此处显式钉死防误开）
# ---------------------------------------------------------------------------
cp.ENABLE_DITHER = False

# ---------------------------------------------------------------------------
# [6] 真机新增常量（RealB601Backend / safety 使用）
# ---------------------------------------------------------------------------
BUS_RATE_HZ = 500.0            # 总线线程频率 [Hz]（rebotarm_dm.yaml rate）
BUS_DT = 1.0 / BUS_RATE_HZ     # 总线周期 [s]
TORQUE_RAMP_TIME = 0.5         # 使能后力矩混入斜坡 [s]：g(q) -> 全控制线性过渡，
                               #   防使能瞬间力矩阶跃甩臂
TORQUE_SLEW_MAX = 200.0        # 力矩斜率限制 [N*m/s]（500 Hz 下每拍 0.4 N*m；
                               #   保护 M6≈4e-4 kg*m^2 的轻腕关节）
WATCHDOG_TIMEOUT = 0.05        # 控制线程心跳超时 [s]：超期总线层自动降级
                               #   纯重力补偿（比保持失控力矩安全）
CONTACT_RESID_TAU = 8.0        # |tau_meas - tau_cmd| 碰撞/卡滞残差阈值 [N*m]
CONTACT_RESID_COUNT = 50       # 残差连续超阈拍数（控制步）才触发急停
                               #   （100 Hz 下 0.5 s，滤除接触瞬态尖峰）
VEL_SPIKE_MAX = 6.0            # 关节速度异常阈值 [rad/s]（> 2*QDOT_MAX 首跑值，
                               #   编码器跳变/失控征兆 -> 急停）
Q_BRINGUP_TOL = 0.02           # reset_to 构型校验容差 [rad]（真机无 teleport，
                               #   须先由 POS_VEL 就位脚本摆到 Q_INIT）

# MIT 模式安全网增益（下发层）：kp=0 纯力矩前馈；kd 留小阻尼兜底，
# 叠加在驱动器电流环之上，等效加深 JOINT_DAMPING 但不经控制律
MIT_KP = np.zeros(6)
MIT_KD = np.array([0.5, 0.5, 0.5, 0.1, 0.1, 0.1])
